const SEED_TIMESTAMP = "2026-01-15T08:00:00.000Z";

function buildDeck({ id, title, description, topicId, color, cards }) {
  const normalizedCards = cards.map((card, index) => ({
    ...card,
    deckId: id,
    topicId,
    masteryLevel: 0,
    reviewCount: 0,
    lastReviewedAt: null,
    position: index,
    createdAt: SEED_TIMESTAMP,
    updatedAt: SEED_TIMESTAMP,
  }));

  return {
    id,
    title,
    description,
    topicId,
    color,
    isDefault: true,
    cards: normalizedCards,
    cardCount: normalizedCards.length,
    createdAt: SEED_TIMESTAMP,
    updatedAt: SEED_TIMESTAMP,
  };
}

