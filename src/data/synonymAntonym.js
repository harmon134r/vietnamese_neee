/**
 * Filter Synonym/Antonym Chase items by game mode and optional topicId.
 *
 * @param {{ mode?: "synonym" | "antonym" | "mixed", topicId?: string }} [options]
 * @returns {Array<(typeof SYNONYM_ANTONYM_ITEMS)[number]>}
 */
export function getChaseItems({ mode = "synonym", topicId = "all" } = {}) {
  const normalizedMode = typeof mode === "string" ? mode.trim().toLowerCase() : "synonym";
  const normalizedTopic = typeof topicId === "string" ? topicId.trim().toLowerCase() : "all";

  return SYNONYM_ANTONYM_ITEMS.filter((item) => {
    const matchesMode =
      normalizedMode === "mixed" || normalizedMode === "all"
        ? true
        : item.mode === normalizedMode;
    const matchesTopic =
      !normalizedTopic || normalizedTopic === "all"
        ? true
        : item.topicId === normalizedTopic;
    return matchesMode && matchesTopic;
  });
}
